/**
 * Hook bridge.
 *
 * Session colour is driven by the CLIs telling us what they are doing, not by
 * scraping their TUIs:
 *   Claude → `--settings` injects command hooks (UserPromptSubmit, Notification,
 *            Stop, SessionEnd, …) that POST here.
 *   Codex  → `-c notify=[...]` points at a shim that POSTs here on turn end.
 *
 * Neither mechanism touches the user's global config. The shim scripts are
 * generated at runtime with absolute paths baked in, and they re-enter this same
 * Electron binary as plain Node (ELECTRON_RUN_AS_NODE), so there is no
 * dependency on a system Node install.
 */

import http from 'node:http'
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { EventEmitter } from 'node:events'
import { hostCapture, hostKind, toHostPath } from './host.js'

export interface HookEvent {
  /** Our session id, carried through the tmux environment. */
  termSessionId: string
  source: 'claude' | 'codex'
  event: string
  payload: Record<string, unknown>
  receivedAt: number
}

/** The hook runner script, written to disk at startup. */
const HOOK_SCRIPT = `#!/usr/bin/env node
// Generated by Workbench. Relays CLI hook/notify events to the running app.
const fs = require('fs')
const http = require('http')

const source = process.argv[2] || 'claude'
const eventArg = process.argv[3] || ''
const termSessionId = process.env.TERMINAL_SESSION_ID
const bridgeFile = process.env.TERMINAL_BRIDGE_FILE

// Never block or fail the agent because our listener is down.
function bail() { process.exit(0) }
if (!termSessionId || !bridgeFile) bail()

// Resolved at invocation time, not at tmux-session creation time. The app can
// restart (new port, new token) while these tmux sessions keep running, so a
// value baked into the environment would be stale within one \`npm run dev\`.
function bridge() {
  try {
    const b = JSON.parse(fs.readFileSync(bridgeFile, 'utf8'))
    if (!b || typeof b.port !== 'number' || typeof b.token !== 'string') return null
    if (!b.port || !b.token) return null
    return b
  } catch { return null }
}

function post(body) {
  const b = bridge()
  if (!b) bail()
  try {
    const data = Buffer.from(JSON.stringify(body))
    const req = http.request(
      {
        host: '127.0.0.1',
        port: b.port,
        path: '/event',
        method: 'POST',
        timeout: 2000,
        headers: {
          'content-type': 'application/json',
          'content-length': data.length,
          'x-terminal-token': b.token
        }
      },
      (res) => { res.resume(); res.on('end', bail) }
    )
    req.on('error', bail)
    req.on('timeout', bail)
    req.write(data)
    req.end()
  } catch { bail() }
  setTimeout(bail, 2500).unref?.()
}

if (source === 'codex') {
  // Codex appends its JSON payload as the final argv entry.
  let payload = {}
  const last = process.argv[process.argv.length - 1]
  try { payload = JSON.parse(last) } catch { payload = { raw: String(last || '') } }
  post({ termSessionId, source, event: String(payload.type || 'agent-turn-complete'), payload })
} else {
  // Claude delivers the hook payload on stdin as JSON.
  let buf = ''
  process.stdin.setEncoding('utf8')
  process.stdin.on('data', (c) => { buf += c; if (buf.length > 2e6) buf = buf.slice(0, 2e6) })
  process.stdin.on('end', () => {
    let payload = {}
    try { payload = JSON.parse(buf) } catch { payload = { raw: buf.slice(0, 4000) } }
    const event = eventArg || String(payload.hook_event_name || 'Unknown')
    post({ termSessionId, source: 'claude', event, payload })
  })
  process.stdin.on('error', bail)
  setTimeout(bail, 4000).unref?.()
}
`

/**
/**
 * The `workbench` command agents get on their PATH.
 *
 * One binary, three verbs, because there is only one name to claim: `list` and
 * `send` reach the other sessions in this window, `show` puts a file in the
 * preview pane. They arrived from two different branches and collided on the
 * filename; merging them is cheaper than teaching agents two commands.
 *
 * An agent cannot be handed a port and a token at launch — both rotate every
 * time the app starts, and tmux bakes the environment in once. So this resolves
 * the endpoint at invocation time from the same bridge file the hooks use.
 *
 * Mounted routes return `{ ok, value | error }`. The communication commands
 * also accept older flat replies so a detached shell survives an app upgrade;
 * the preview command keeps its own success envelope intact.
 */
const WORKBENCH_CLI_SCRIPT = `#!/usr/bin/env node
// Generated by Workbench. Lets an agent talk to the other sessions and show files.
const fs = require('fs')
const path = require('path')
const http = require('http')

const argv = process.argv.slice(2)
const cmd = argv.shift()
const sessionId = process.env.TERMINAL_SESSION_ID
const credential = process.env.TERMINAL_BUS_TOKEN || ''
const bridgeFile = process.env.TERMINAL_BRIDGE_FILE

function die(msg) { process.stderr.write(msg + '\\n'); process.exit(1) }
function misuse(msg) { process.stderr.write(msg + '\\n'); process.exit(2) }

const USAGE = [
  'workbench — reach the other agent sessions, and show files to the user',
  '',
  '  workbench list',
  '      Show every session you can reach, with the @name to use.',
  '',
  '  workbench send @name "message" [--wait] [--timeout SECONDS]',
  '      Send a prompt to another session. With --wait, block until that',
  '      session finishes its turn and print its reply to stdout.',
  '',
  '  workbench show <file>',
  '      Open a file in the preview pane on the right.',
  '',
  'Exit status is 0 only when a --wait send came back with a reply.'
].join('\\n')

if (!cmd || cmd === '--help' || cmd === '-h' || cmd === 'help') {
  process.stdout.write(USAGE + '\\n')
  process.exit(0)
}
if (!sessionId || !bridgeFile) die('workbench: not running inside a Workbench session')

function bridge() {
  try {
    const b = JSON.parse(fs.readFileSync(bridgeFile, 'utf8'))
    if (!b || typeof b.port !== 'number' || typeof b.token !== 'string') return null
    if (!b.port || !b.token) return null
    return b
  } catch { return null }
}

function call(path, body, timeoutMs) {
  return new Promise((resolve, reject) => {
    const b = bridge()
    if (!b) return reject(new Error('Workbench is not running.'))
    const data = Buffer.from(JSON.stringify(credential && path !== '/preview/show' ? { ...body, credential } : body))
    const req = http.request(
      {
        host: '127.0.0.1',
        port: b.port,
        path: path,
        method: 'POST',
        // The app answers a blocking relay only when the other agent is done,
        // so this has to outlast the relay's own timeout rather than race it.
        timeout: timeoutMs,
        headers: {
          'content-type': 'application/json',
          'content-length': data.length,
          'x-terminal-token': b.token
        }
      },
      (res) => {
        let buf = ''
        res.setEncoding('utf8')
        res.on('data', (c) => { buf += c })
        res.on('end', () => {
          try {
            const result = JSON.parse(buf)
            if (path === '/preview/show') resolve(result)
            else if (result.ok === false) reject(new Error(result.error || 'Workbench refused this call.'))
            else resolve(result.ok === true && 'value' in result ? result.value : result)
          }
          catch { reject(new Error('Bad response from Workbench.')) }
        })
      }
    )
    req.on('error', (e) => reject(e))
    req.on('timeout', () => { req.destroy(new Error('Workbench did not respond in time.')) })
    req.write(data)
    req.end()
  })
}

async function main() {
  if (cmd === 'show') {
    const target = argv[0]
    if (!target) misuse('usage: workbench show <file>')
    // A relative target resolves against the current directory, which is right
    // everywhere: on Windows this script runs as a native process even though
    // the agent that called it lives in WSL, and interop hands it the UNC
    // spelling of the agent's directory. An absolute POSIX target is the case
    // that breaks — Windows would resolve it against the current drive — so it
    // travels untouched and the app translates the spelling once, at its own
    // boundary.
    const abs = target.charAt(0) === '/' ? target : path.resolve(target)
    // Showing a file is a courtesy, never something an agent should have to
    // handle failing, so this stays quiet and quick.
    const r = await call(
      '/preview/show',
      { termSessionId: sessionId, path: abs },
      8000
    )
    if (r && r.ok) {
      process.stdout.write('Showing ' + path.basename(target) + ' in the preview pane.\\n')
      return 0
    }
    process.stderr.write('workbench: ' + ((r && r.error) || 'could not show that file') + '\\n')
    return 1
  }

  if (cmd === 'list') {
    const r = await call('/sessions', { termSessionId: sessionId }, 15000)
    const rows = (r && r.sessions) || []
    if (rows.length === 0) { process.stdout.write('No other sessions.\\n'); return 0 }
    const w = Math.max.apply(null, rows.map((s) => s.mention.length))
    for (const s of rows) {
      const pad = ' '.repeat(w - s.mention.length)
      const self = s.self ? '  (you)' : ''
      process.stdout.write('@' + s.mention + pad + '  ' + s.agent + '  ' + s.status + self + '\\n')
    }
    return 0
  }

  if (cmd !== 'send') misuse('Unknown command "' + cmd + '".\\n\\n' + USAGE)

  let wait = false
  let timeoutSec = 600
  const rest = []
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (a === '--wait' || a === '-w') { wait = true; continue }
    if (a === '--no-wait') { wait = false; continue }
    if (a === '--timeout' || a === '-t') { timeoutSec = Number(argv[++i]) || timeoutSec; continue }
    rest.push(a)
  }
  const to = rest.shift()
  if (!to) die('Who to? Usage: workbench send @name "message" [--wait]')
  const message = rest.join(' ')
  if (!message.trim()) die('Nothing to send.')

  const r = await call(
    '/relay',
    { termSessionId: sessionId, to: to, message: message, wait: wait, timeoutMs: timeoutSec * 1000 },
    wait ? timeoutSec * 1000 + 30000 : 30000
  )
  if (!r) die('No response from Workbench.')
  if (r.error && !r.phase) die(r.error)

  if (r.phase === 'replied') {
    process.stdout.write(r.reply ? r.reply + '\\n' : '(the session finished but said nothing)\\n')
    return r.reply ? 0 : 1
  }
  if (r.phase === 'delivered') {
    process.stdout.write('Delivered to ' + r.toTitle + '.\\n')
    return 0
  }
  if (r.phase === 'waiting') {
    process.stderr.write(r.toTitle + ' stopped and needs a human: ' + (r.reason || 'awaiting input') + '\\n')
    return 1
  }
  process.stderr.write((r.error || 'Relay failed') + '\\n')
  return 1
}

main().then((code) => process.exit(code), (e) => die(e.message))
`

export interface HookPaths {
  /** Directory holding the generated scripts; goes on each agent's PATH. */
  binDir: string
  hookScript: string
  /** The `workbench` command agents run: list, send, and show. */
  cli: string
  claudeShim: string
  codexShim: string
  claudeSettings: string
  /** Stable path holding the *current* endpoint + token. Read on every hook. */
  bridgeFile: string
}

/** What the hook runner reads out of the bridge file. */
export interface BridgeManifest {
  version: number
  port: number
  token: string
  /** The app instance that owns this endpoint — useful when diagnosing staleness. */
  pid: number
  startedAt: number
}

const BRIDGE_VERSION = 1

/** Every path the bridge answers on. Anything else is a 404. */
const ROUTES = ['/event', '/relay', '/sessions']

/**
 * Writes `data` to `file` atomically, readable only by the owner.
 *
 * The token lives in this file, so the temp file is created 0600 *before* it
 * holds anything — a `writeFile` + `chmod` pair leaves a window where the token
 * is world-readable.
 */
function writeSecretAtomic(file: string, data: string): void {
  const tmp = `${file}.${process.pid}.tmp`
  const fd = fs.openSync(tmp, 'wx', 0o600)
  try {
    fs.writeFileSync(fd, data, 'utf8')
    fs.fsyncSync(fd)
  } finally {
    fs.closeSync(fd)
  }
  fs.renameSync(tmp, file)
}

/** Reads a bridge manifest, or null if absent/unreadable/malformed. */
export function readBridgeManifest(file: string): BridgeManifest | null {
  try {
    const b = JSON.parse(fs.readFileSync(file, 'utf8')) as Partial<BridgeManifest>
    if (typeof b.port !== 'number' || !b.port) return null
    if (typeof b.token !== 'string' || !b.token) return null
    return {
      version: typeof b.version === 'number' ? b.version : 0,
      port: b.port,
      token: b.token,
      pid: typeof b.pid === 'number' ? b.pid : 0,
      startedAt: typeof b.startedAt === 'number' ? b.startedAt : 0
    }
  } catch {
    return null
  }
}

/** A JSON POST route mounted on the bridge by another subsystem. */
export type BridgeRoute = (body: unknown) => Promise<unknown>

export class HookBridge extends EventEmitter {
  private server: http.Server | null = null
  /**
   * Extra routes, all behind the same token check as `/event`.
   *
   * The Session Bus mounts `/bus/call` here rather than opening a second
   * listener: one loopback port, one rotating token, one thing to reason about.
   */
  private routes = new Map<string, BridgeRoute>()
  /** Rotated every launch — a leaked token dies with the app instance. */
  readonly token = crypto.randomBytes(24).toString('hex')
  private _port = 0
  readonly paths: HookPaths
  private binDir: string
  private electronExecPath: string

  constructor(binDir: string, electronExecPath: string) {
    super()
    this.binDir = binDir
    this.electronExecPath = electronExecPath
    this.paths = {
      binDir,
      hookScript: path.join(binDir, 'hook.cjs'),
      cli: path.join(binDir, 'workbench'),
      claudeShim: path.join(binDir, 'claude-hook.sh'),
      codexShim: path.join(binDir, 'codex-notify.sh'),
      claudeSettings: path.join(binDir, 'claude-settings.json'),
      bridgeFile: path.join(binDir, 'bridge.json')
    }
  }

  get port(): number {
    return this._port
  }

  /** Where the generated CLIs live. Goes on the PATH of every session. */
  get bin(): string {
    return this.binDir
  }

  /** Mounts a token-protected JSON POST route. */
  route(path: string, handler: BridgeRoute): void {
    this.routes.set(path, handler)
  }

  /**
   * Env every agent session needs so its hooks can phone home.
   *
   * Deliberately carries no port and no token: both change on every app launch,
   * and tmux bakes this environment in at session-creation time. Only the two
   * genuinely stable facts travel here — who the session is, and where to look
   * up the endpoint.
   */
  envFor(termSessionId: string): Record<string, string> {
    return {
      TERMINAL_SESSION_ID: termSessionId,
      // Host spelling: this is planted in the tmux environment, which lives on
      // the host, and read by scripts the host launches. On Windows the shims
      // hand it back across interop with WSLENV's `/p` flag, which translates
      // it into the UNC path the native process can actually open.
      TERMINAL_BRIDGE_FILE: toHostPath(this.paths.bridgeFile)
    }
  }

  async start(): Promise<void> {
    this.writeScripts()
    await new Promise<void>((resolve, reject) => {
      const server = http.createServer((req, res) => this.handle(req, res))
      server.on('error', reject)
      // Port 0 → OS picks a free one; loopback only.
      server.listen(0, '127.0.0.1', () => {
        const addr = server.address()
        this._port = typeof addr === 'object' && addr ? addr.port : 0
        this.server = server
        resolve()
      })
    })
    this.publishBridgeFile()
  }

  /**
   * Points every existing agent at this launch's endpoint. Agents adopted from a
   * previous run pick it up on their next hook invocation with no restart.
   */
  publishBridgeFile(): void {
    const manifest: BridgeManifest = {
      version: BRIDGE_VERSION,
      port: this._port,
      token: this.token,
      pid: process.pid,
      startedAt: Date.now()
    }
    fs.mkdirSync(this.binDir, { recursive: true })
    // A crashed previous run can leave a temp file behind; `wx` would then fail.
    try {
      fs.rmSync(`${this.paths.bridgeFile}.${process.pid}.tmp`, { force: true })
    } catch {
      /* nothing to clean up */
    }
    writeSecretAtomic(this.paths.bridgeFile, JSON.stringify(manifest))
  }

  async stop(): Promise<void> {
    // Remove the endpoint before closing it, so a hook firing during shutdown
    // bails immediately instead of dialling a socket that is going away.
    try {
      fs.rmSync(this.paths.bridgeFile, { force: true })
    } catch {
      /* best effort — a stale file is harmless, the token is already dead */
    }
    if (!this.server) return
    await new Promise<void>((resolve) => this.server!.close(() => resolve()))
    this.server = null
  }

  private handle(req: http.IncomingMessage, res: http.ServerResponse): void {
    const route = req.url ?? ''
    const mounted = route ? this.routes.get(route) : undefined
    if (req.method !== 'POST' || (!ROUTES.includes(route) && !mounted)) {
      res.writeHead(404).end()
      return
    }
    // The token is checked before the route runs, and before any body is read.
    if (req.headers['x-terminal-token'] !== this.token) {
      res.writeHead(403).end()
      return
    }
    if (mounted) {
      this.serveRoute(req, res, mounted)
      return
    }
    // A blocking relay holds this response open until the other agent finishes
    // its turn, which can be many minutes. Node's default socket timeout would
    // cut that off well before the work is done.
    if (route !== '/event') {
      req.socket.setTimeout(0)
      res.setTimeout(0)
    }
    let body = ''
    req.on('data', (c) => {
      body += c
      if (body.length > 4e6) req.destroy()
    })
    req.on('end', () => {
      if (route === '/relay' || route === '/sessions') {
        this.handleAsk(route, body, res)
        return
      }
      res.writeHead(200, { 'content-type': 'application/json' }).end('{"ok":true}')
      try {
        const parsed = JSON.parse(body) as {
          termSessionId?: string
          source?: string
          event?: string
          payload?: Record<string, unknown>
        }
        if (!parsed.termSessionId) return
        const evt: HookEvent = {
          termSessionId: parsed.termSessionId,
          source: parsed.source === 'codex' ? 'codex' : 'claude',
          event: parsed.event ?? 'Unknown',
          payload: parsed.payload ?? {},
          receivedAt: Date.now()
        }
        this.emit('hook', evt)
      } catch {
        /* malformed payload — ignore */
      }
    })
  }

  /**
   * Runs a mounted route: read a JSON body, answer with `{ ok, value | error }`.
   *
   * Errors cross as data rather than as a status code, because the caller is an
   * agent that should be told what it did wrong, not a client that should retry.
   */
  private serveRoute(
    req: http.IncomingMessage,
    res: http.ServerResponse,
    handler: BridgeRoute
  ): void {
    let body = ''
    req.on('data', (c) => {
      body += c
      if (body.length > 4e6) req.destroy()
    })
    req.on('end', () => {
      const answer = (payload: unknown): void => {
        if (res.writableEnded) return
        res.writeHead(200, { 'content-type': 'application/json' }).end(JSON.stringify(payload))
      }
      let parsed: unknown
      try {
        parsed = JSON.parse(body)
      } catch {
        answer({ ok: false, error: 'Malformed request body' })
        return
      }
      handler(parsed).then(
        (value) => answer({ ok: true, value }),
        (err: unknown) => answer({ ok: false, error: err instanceof Error ? err.message : String(err) })
      )
    })
  }

  /**
   * Serves the routes that answer rather than merely accept.
   *
   * `/event` is fire-and-forget by design — a hook must never be able to slow
   * an agent down. These two are the opposite: the caller is an agent that
   * asked a question and is waiting for the answer, so the response is written
   * only once a listener has produced one.
   */
  private handleAsk(route: string, body: string, res: http.ServerResponse): void {
    let parsed: Record<string, unknown>
    try {
      parsed = JSON.parse(body) as Record<string, unknown>
    } catch {
      res.writeHead(400, { 'content-type': 'application/json' }).end('{"error":"bad json"}')
      return
    }
    const termSessionId = typeof parsed.termSessionId === 'string' ? parsed.termSessionId : ''
    if (!termSessionId) {
      res.writeHead(400, { 'content-type': 'application/json' }).end('{"error":"no session"}')
      return
    }

    let answered = false
    const reply = (value: unknown): void => {
      if (answered) return
      answered = true
      try {
        res.writeHead(200, { 'content-type': 'application/json' }).end(JSON.stringify(value))
      } catch {
        /* the agent went away mid-relay; nothing to do */
      }
    }
    // If the caller hangs up we still have to unblock the listener's promise,
    // or a killed agent leaves the relay it started holding a session hostage.
    res.on('close', () => {
      answered = true
    })

    const event = route === '/relay' ? 'relay' : 'sessions-query'
    if (this.listenerCount(event) === 0) {
      reply({ error: 'Workbench is not ready for relays yet.' })
      return
    }
    this.emit(event, { termSessionId, body: parsed }, reply)
  }

  /**
   * Writes the hook runner plus two shell shims. The shims exist so both CLIs can
   * invoke us the way each prefers: Claude runs a shell command string, Codex
   * execs an argv array with no shell, so neither can set env inline.
   */
  private writeScripts(): void {
    fs.mkdirSync(this.binDir, { recursive: true })
    fs.writeFileSync(this.paths.hookScript, HOOK_SCRIPT, { mode: 0o755 })
    // `workbench` is a shell wrapper for the same reason the hook shims are:
    // it has to re-enter this Electron binary as Node, and an agent typing
    // `workbench send …` cannot be expected to set ELECTRON_RUN_AS_NODE first.
    fs.writeFileSync(`${this.paths.cli}.cjs`, WORKBENCH_CLI_SCRIPT, { mode: 0o755 })

    const q = (s: string): string => `'${s.replace(/'/g, `'\\''`)}'`

    // What a shim has to say depends on whether its two halves live on the same
    // side of the boundary.
    //
    // Local host: the shim, the Electron binary and the script share one
    // filesystem, and `env VAR=1 electron hook.cjs …` is the whole story.
    //
    // WSL host: the shim runs inside the distro, but the Electron binary is a
    // Windows process, so the exec crosses interop and three things change. The
    // binary is named the way the distro reaches it (`/mnt/c/…`); the script is
    // named the way *Windows* will open it (the `\\wsl.localhost\…` spelling,
    // which is what this process already holds); and the environment has to be
    // told to travel, because WSL forwards nothing to a Win32 child unless
    // WSLENV lists it. `/w` means "outbound only", and the extra `p` on
    // TERMINAL_BRIDGE_FILE means "and translate the value as a path" — that is
    // what turns the POSIX bridge-file path back into one the Windows process
    // can open.
    //
    // Interop is also why the bridge stays plain HTTP on Windows loopback
    // instead of growing a second transport: WSL 2 is NAT'd by default, so a
    // process inside the distro cannot reach a listener on the Windows side's
    // 127.0.0.1. By the time the hook script runs it *is* a Windows process,
    // talking to a Windows port, and so it needs no Windows knowledge of its
    // own.
    const wsl = hostKind() === 'wsl'
    const wslenv = 'WSLENV=ELECTRON_RUN_AS_NODE/w:TERMINAL_SESSION_ID/w:TERMINAL_BRIDGE_FILE/wp:TERMINAL_BUS_TOKEN/w'
    const exe = wsl ? toHostPath(this.electronExecPath) : this.electronExecPath
    const run = (script: string, tail: string): string =>
      [
        '#!/bin/sh',
        '# Generated by Workbench.',
        `exec env ${wsl ? `${wslenv} ` : ''}ELECTRON_RUN_AS_NODE=1 ${q(exe)} ${q(script)} ${tail}`,
        ''
      ].join('\n')

    const shim = (source: string): string => run(this.paths.hookScript, `${source} "$@"`)

    fs.writeFileSync(this.paths.claudeShim, shim('claude'), { mode: 0o755 })
    fs.writeFileSync(this.paths.codexShim, shim('codex'), { mode: 0o755 })
    fs.writeFileSync(this.paths.cli, run(`${this.paths.cli}.cjs`, '"$@"'), { mode: 0o755 })

    // Node ignores `mode` on win32, so on a WSL host all three land 0644 inside
    // the distro and the agent gets "Permission denied" the first time a hook
    // fires. The execute bit has to be set from the side that owns the inode.
    if (wsl) {
      hostCapture([
        'chmod',
        '755',
        toHostPath(this.paths.claudeShim),
        toHostPath(this.paths.codexShim),
        toHostPath(this.paths.cli)
      ])
    }
  }

  /**
   * One settings file serves every Claude session — the hook learns which session
   * it belongs to from TERMINAL_SESSION_ID in the tmux environment.
   */
  writeClaudeSettings(): string {
    // Claude runs this string through its own shell, on the host, so the shim
    // is named the way the host names it rather than the way we hold it.
    const shimPath = toHostPath(this.paths.claudeShim)
    const cmd = (event: string): string => `'${shimPath.replace(/'/g, `'\\''`)}' ${event}`

    const entry = (event: string): unknown => [
      { hooks: [{ type: 'command', command: cmd(event), timeout: 5 }] }
    ]

    const settings = {
      $schema: 'https://json.schemastore.org/claude-code-settings.json',
      hooks: {
        SessionStart: entry('SessionStart'),
        UserPromptSubmit: entry('UserPromptSubmit'),
        PreToolUse: entry('PreToolUse'),
        PostToolUse: entry('PostToolUse'),
        Notification: entry('Notification'),
        Stop: entry('Stop'),
        SubagentStop: entry('SubagentStop'),
        SessionEnd: entry('SessionEnd')
      }
    }
    fs.writeFileSync(this.paths.claudeSettings, JSON.stringify(settings, null, 2), 'utf8')
    return this.paths.claudeSettings
  }
}
